// The method hooks are proven the way the rest of this package proves a runtime
// slice: the emitted Go is built into a real binary, the source is deleted, and
// the binary is run against an empty PATH and compared with the engine running
// the same Bash++ program — exact stdout, exact stderr and exact status. A test
// that only searched the emitted text for substrings would have accepted Go
// that does not parse, so nothing here asserts on emitted text alone.
//
// methodUnit is the test's stand-in for the three delegations a dispatcher owner
// adds: a method declaration to runtimeMethodFunction, a method call to
// runtimeMethodCall, and a captured method value to runtimeMethodHandle. Every
// other statement is lowered by the ordinary emitter, so the artifacts differ
// from a fully wired compiler only in who chose those three branches.
type methodUnit struct {
	e *emitter
	// receivers is the static receiver type a call site resolves, which a wired
	// dispatcher reads from its projections. Declared variables are enough for
	// these fixtures and keep the resolution visible in the test.
	receivers map[string]string
	blocks    int
}

func newMethodUnit(file *syntax.File) *methodUnit {
	e := &emitter{
		options:         Options{Package: "main", Runtime: DefaultRuntime},
		prefix:          "__bpp0_",
		writtenNames:    map[string]bool{},
		inferredParams:  map[*syntax.BashPPField]string{},
		declaredTypes:   map[string]*syntax.BashPPDecl{},
		functionDecls:   map[string]*syntax.BashPPFuncDecl{},
		enumMembers:     map[string][]*syntax.Lit{},
		funcs:           map[string]bool{},
		scopes:          []map[string]bool{{}},
		globals:         map[string]bool{},
		visibleGlobals:  map[string]bool{},
		imports:         map[string]string{},
		callableParams:  map[*syntax.BashPPField]string{},
		dotNames:        map[string]bool{},
		declaredGlobals: map[string]bool{},
		typeNames:       map[string]bool{},
	}
	e.projections.projectionPush()
	e.needsExecution(file)
	e.findProjectionWrites(file)
	for _, s := range file.Stmts {
		if f, ok := s.Cmd.(*syntax.BashPPFuncDecl); ok {
			if f.Receiver != nil {
				e.methodDeclarations = append(e.methodDeclarations, f)
			} else {
				e.funcs[f.Name.Value] = true
				e.functionDecls[f.Name.Value] = f
			}
		}
		switch n := s.Cmd.(type) {
		case *syntax.BashPPDecl:
			if n.Kw.Value == "type" {
				e.typeNames[n.Name.Value] = true
				e.declaredTypes[n.Name.Value] = n
			}
			if n.Kw.Value == "var" || n.Kw.Value == "const" {
				e.globals[n.Name.Value] = true
			}
		case *syntax.BashPPShortDecl:
			for _, name := range names(n.Lhs) {
				if name != "_" {
					e.globals[name] = true
				}
			}
		}
	}
	return &methodUnit{e: e, receivers: map[string]string{}}
}

// compile lowers a whole unit. It is a reduced compilePass: the same
// declaration/body split and the same program main, with the method branches
// added.
func (u *methodUnit) compile(file *syntax.File) ([]byte, error) {
	e := u.e
	if !e.execution {
		return nil, fmt.Errorf("fixture does not reach the execution runtime")
	}
	if err := e.discoverCallableParams(file); err != nil {
		return nil, err
	}
	var declarations, body strings.Builder
	for _, s := range file.Stmts {
		switch n := s.Cmd.(type) {
		case *syntax.BashPPFuncDecl:
			text, err := u.function(n)
			if err != nil {
				return nil, err
			}
			declarations.WriteString(text)
		case *syntax.BashPPDecl:
			if n.Kw.Value == "type" {
				typ, err := e.declarationType(n)
				if err != nil {
					return nil, err
				}
				declarations.WriteString(e.mark(n) + typ + "\n")
				continue
			}
			if n.DeclType != nil {
				u.receivers[n.Name.Value] = n.DeclType.Value
			}
			text, err := e.globalStatement(s)
			if err != nil {
				return nil, err
			}
			body.WriteString(text)
		default:
			text, err := u.statement(s)
			if err != nil {
				return nil, err
			}
			body.WriteString(text)
		}
	}
	var raw strings.Builder
	fmt.Fprintf(&raw, "// Code generated by mvdan.cc/sh/v3/lower. DO NOT EDIT.\npackage main\n")
	e.output = true
	fmt.Fprintf(&raw, "import %sfmt \"fmt\"\n", e.prefix)
	fmt.Fprintf(&raw, "import %srt %s\n", e.prefix, strconv.Quote(e.options.Runtime))
	fmt.Fprintf(&raw, "import %sos \"os\"\n", e.prefix)
	raw.WriteString(e.importLines())
	if len(e.globals) > 0 {
		fmt.Fprintf(&raw, "var %sprogram *%srt.Program\n", e.prefix, e.prefix)
	}
	raw.WriteString(e.globalDecls.String())
	raw.WriteString(declarations.String())
	raw.WriteString(e.programMain(body.String()))
	text := strings.ReplaceAll(raw.String(), "/*"+e.prefix+"reset*/", e.program()+".SetStatus(0)\n")
	text = strings.ReplaceAll(text, "/*"+e.prefix+"status0*/", e.program()+".SetStatus(0);")
	text = strings.ReplaceAll(text, "/*"+e.prefix+"status1*/", e.program()+".SetStatus(1);")
	source, err := format.Source([]byte(text))
	if err != nil {
		return nil, fmt.Errorf("emitted Go does not parse: %w\n%s", err, text)
	}
	return source, nil
}

// function lowers a declaration, routing a method to runtimeMethodFunction with
// the same prologue e.function establishes for a free callable.
func (u *methodUnit) function(f *syntax.BashPPFuncDecl) (string, error) {
	e := u.e
	if f.Receiver == nil {
		return e.function(f)
	}
	saved, savedProjections, savedFunc := e.scopes, e.projections, e.inFunc
	e.inFunc = true
	e.projections = projector{}
	e.projections.projectionPush()
	e.projections.projectionPush()
	e.scopes = []map[string]bool{{}}
	defer func() { e.scopes, e.projections, e.inFunc = saved, savedProjections, savedFunc }()
	name, typ := receiverSpelling(f.Receiver)
	e.bind(name)
	e.projections.projectionBind(name, e.projectionType(typ, nil))
	// A method's own type parameters are in scope over its signature and body
	// exactly as a free callable's are; e.function binds them the same way.
	for _, p := range f.TypeParams {
		for _, n := range p.Names {
			e.bind(n.Value)
		}
	}
	signature, err := e.signature(f.Params, f.Results, f.Body)
	if err != nil {
		return "", err
	}
	savedResults := e.resultTypes
	e.resultTypes = e.returnTypes(f.Results)
	defer func() { e.resultTypes = savedResults }()
	body, err := e.block(f.Body)
	if err != nil {
		return "", err
	}
	generics, err := e.typeParams(f.TypeParams)
	if err != nil {
		return "", err
	}
	return e.runtimeMethodFunction(f, signature, body, generics)
}

func (u *methodUnit) statement(s *syntax.Stmt) (string, error) {
	e := u.e
	switch n := s.Cmd.(type) {
	case *syntax.BashPPAgenticBlock:
		child := fmt.Sprintf("%sblockProgram%d", e.prefix, u.blocks)
		u.blocks++
		parent := e.program()
		previous := e.programExpr
		e.programExpr = child
		defer func() { e.programExpr = previous }()
		var inner strings.Builder
		for _, stmt := range n.Body.Stmts {
			text, err := u.statement(stmt)
			if err != nil {
				return "", err
			}
			inner.WriteString(text)
		}
		return e.mark(n) + child + " := " + parent + ".Block()\n_ = " + child + "\n" + inner.String(), nil
	case *syntax.BashPPCall:
		if len(n.Fun) != 2 {
			break
		}
		text, err := e.runtimeMethodCall(n, u.receivers[n.Fun[0].Value])
		if err != nil {
			return "", err
		}
		return e.mark(n) + text + "\n", nil
	case *syntax.BashPPShortDecl:
		if n.Call != nil && len(n.Call.Fun) == 2 {
			rhs, err := e.runtimeMethodCall(n.Call, u.receivers[n.Call.Fun[0].Value])
			if err != nil {
				return "", err
			}
			ns := names(n.Lhs)
			for i, name := range ns {
				e.bind(name)
				e.projections.projectionBind(name, e.callProjection(n.Call, i))
			}
			return e.mark(n) + e.program() + ".SetStatus(0)\n" + strings.Join(ns, ", ") + " := " + rhs + e.unused(ns) + "\n", nil
		}
		if len(n.MethodValue) != 2 || len(n.Lhs) != 1 {
			break
		}
		receiver, method := n.MethodValue[0].Value, n.MethodValue[1].Value
		typ, err := e.runtimeMethodHandleType(n, u.receivers[receiver], method)
		if err != nil {
			return "", err
		}
		handle, err := e.runtimeMethodHandle(n, receiver, u.receivers[receiver], method)
		if err != nil {
			return "", err
		}
		target := n.Lhs[0].Value
		e.globalDecls.WriteString(e.mark(n) + "var " + target + " " + typ + "\n")
		e.declaredGlobals[target] = true
		e.visibleGlobals[target] = true
		e.globals[target] = true
		return e.mark(n) + "/*" + e.prefix + "reset*/" + target + " = " + handle + "\n", nil
	}
	return e.statement(s)
}

// The agentic-block program is the frame a call inside it is checked against.
// A wired dispatcher reaches it through e.agenticBlock; the fixtures only need
// the same nesting, which u.statement above reproduces.

func parseMethodFixture(t *testing.T, source string) *syntax.File {
	t.Helper()
	file, err := syntax.NewParser(syntax.Variant(syntax.LangBashPP)).Parse(strings.NewReader(source), "methods.bpp")
	if err != nil {
		t.Fatal(err)
	}
	return file
}

func lowerMethodFixture(t *testing.T, source string) []byte {
	t.Helper()
	file := parseMethodFixture(t, source)
	unit := newMethodUnit(file)
	emitted, err := unit.compile(file)
	if err != nil {
		t.Fatal(err)
	}
	return emitted
}

type methodOutcome struct {
	stdout, stderr string
	status         int
}

// runMethodArtifact builds the emitted Go, removes the source so nothing but
// the binary can be observed, and runs it with no usable PATH.
func runMethodArtifact(t *testing.T, ctx context.Context, source []byte) methodOutcome {
	t.Helper()
	dir := t.TempDir()
	_, this, _, _ := runtime.Caller(0)
	root := filepath.Dir(filepath.Dir(this))
	module := "module methodartifact\n\ngo " + strings.TrimPrefix(runtime.Version(), "go") +
		"\n\nrequire mvdan.cc/sh/v3 v3.0.0\nreplace mvdan.cc/sh/v3 => " + filepath.ToSlash(root) + "\n"
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte(module), 0600); err != nil {
		t.Fatal(err)
	}
	generated := filepath.Join(dir, "generated.go")
	if err := os.WriteFile(generated, source, 0600); err != nil {
		t.Fatal(err)
	}
	binary := filepath.Join(dir, "program")
	build := exec.CommandContext(ctx, filepath.Join(runtime.GOROOT(), "bin", "go"), "build", "-mod=mod", "-o", binary, "generated.go")
	build.Dir = dir
	build.Env = append(os.Environ(), "GOWORK=off", "GOTOOLCHAIN=local")
	if out, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build: %v\n%s\n%s", err, out, source)
	}
	if err := os.Remove(generated); err != nil {
		t.Fatal(err)
	}
	command := exec.CommandContext(ctx, binary)
	command.Dir = t.TempDir()
	command.Env = []string{"PATH="}
	var stdout, stderr bytes.Buffer
	command.Stdout = &stdout
	command.Stderr = &stderr
	status := 0
	if err := command.Run(); err != nil {
		var exit *exec.ExitError
		if !errors.As(err, &exit) {
			t.Fatal(err)
		}
		status = exit.ExitCode()
	}
	return methodOutcome{stdout.String(), stderr.String(), status}
}

func runMethodEngine(t *testing.T, ctx context.Context, source string) methodOutcome {
	t.Helper()
	dir := t.TempDir()
	var stdout, stderr bytes.Buffer
	runner, err := interp.New(interp.Lang(syntax.LangBashPP), interp.StdIO(nil, &stdout, &stderr),
		interp.Dir(dir), interp.Env(expand.ListEnviron("PATH=")))
	if err != nil {
		t.Fatal(err)
	}
	status := 0
	if err := runner.Run(ctx, parseMethodFixture(t, source)); err != nil {
		var exit interp.ExitStatus
		if !errors.As(err, &exit) {
			t.Fatal(err)
		}
		status = int(exit)
	}
	return methodOutcome{stdout.String(), stderr.String(), status}
}

