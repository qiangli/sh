// TestRuntimeMethodArtifactParity is the acceptance evidence: every fixture is
// built, stripped of its source, run with an empty PATH, and diffed against the
// engine.
func TestRuntimeMethodArtifactParity(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 4*time.Minute)
	defer cancel()
	for _, tc := range methodFixtures() {
		t.Run(tc.name, func(t *testing.T) {
			emitted := lowerMethodFixture(t, tc.source)
			for _, want := range tc.emitted {
				if !strings.Contains(string(emitted), want) {
					t.Fatalf("emitted Go is missing %q\n%s", want, emitted)
				}
			}
			for _, unwanted := range tc.absent {
				if strings.Contains(string(emitted), unwanted) {
					t.Fatalf("emitted Go still contains %q\n%s", unwanted, emitted)
				}
			}
			artifact := runMethodArtifact(t, ctx, emitted)
			engine := runMethodEngine(t, ctx, tc.source)
			if engine != (methodOutcome{tc.stdout, tc.stderr, tc.status}) {
				t.Fatalf("engine outcome %+v is not the declared one %+v", engine, methodOutcome{tc.stdout, tc.stderr, tc.status})
			}
			if artifact != engine {
				t.Fatalf("artifact %+v engine %+v\n%s", artifact, engine, emitted)
			}
		})
	}
}

// TestRuntimeMethodPublicABIIsOrdinaryGo builds a second package that calls the
// public methods as an ordinary Go consumer would. It proves the public method
// keeps its declared Go signature, that a marked method reached from outside a
// compiled program runs with assistance off, and that a denial is reported once
// rather than repeated by a fallback.
func TestRuntimeMethodPublicABIIsOrdinaryGo(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 4*time.Minute)
	defer cancel()
	emitted := lowerMethodFixture(t, `type Adder struct { n int }
agentic func (a *Adder) sum(x int, y int) (int, int) { return $((x + y)), x }
func (a *Adder) label(prefix string) string { return $prefix }
var a Adder = Adder{}
agentic { a.sum(1, 1); }
`)
	consumer := `package main

import (
	"fmt"
	"os"
)

type foreign struct{}

func (foreign) Show() {}

func main() {
	var a Adder
	total, first := a.sum(4, 5)
	label := a.label("tag")
	fmt.Fprintf(os.Stdout, "public:%d:%d:%s\n", total, first, label)
	var _ interface {
		sum(int, int) (int, int)
		label(string) string
	} = &a
	__bpp0_sourceMain()
}
`
	dir := t.TempDir()
	_, this, _, _ := runtime.Caller(0)
	root := filepath.Dir(filepath.Dir(this))
	module := "module methodconsumer\n\ngo " + strings.TrimPrefix(runtime.Version(), "go") +
		"\n\nrequire mvdan.cc/sh/v3 v3.0.0\nreplace mvdan.cc/sh/v3 => " + filepath.ToSlash(root) + "\n"
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte(module), 0600); err != nil {
		t.Fatal(err)
	}
	// The unit's own main is renamed so the consumer supplies the entry point
	// and the public methods are reached as a foreign Go caller reaches them.
	renamed := strings.Replace(string(emitted), "\nfunc main() {", "\nfunc __bpp0_sourceMain() {", 1)
	if renamed == string(emitted) {
		t.Fatal("emitted unit has no main to rename")
	}
	if err := os.WriteFile(filepath.Join(dir, "generated.go"), []byte(renamed), 0600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "consumer.go"), []byte(consumer), 0600); err != nil {
		t.Fatal(err)
	}
	binary := filepath.Join(dir, "program")
	build := exec.CommandContext(ctx, filepath.Join(runtime.GOROOT(), "bin", "go"), "build", "-mod=mod", "-o", binary, ".")
	build.Dir = dir
	build.Env = append(os.Environ(), "GOWORK=off", "GOTOOLCHAIN=local")
	if out, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build: %v\n%s\n%s", err, out, renamed)
	}
	for _, name := range []string{"generated.go", "consumer.go"} {
		if err := os.Remove(filepath.Join(dir, name)); err != nil {
			t.Fatal(err)
		}
	}
	command := exec.CommandContext(ctx, binary)
	command.Dir = t.TempDir()
	command.Env = []string{"PATH="}
	var stdout, stderr bytes.Buffer
	command.Stdout = &stdout
	command.Stderr = &stderr
	status := 0
	if err := command.Run(); err != nil {
		var exit *exec.ExitError
		if !errors.As(err, &exit) {
			t.Fatal(err)
		}
		status = exit.ExitCode()
	}
	// The public entry to a marked method is its own program, whose frame has
	// assistance off, so the ordinary Go call is denied exactly once and its
	// results are the zero values. An unmarked method has nothing to deny and
	// returns its result through the same public signature.
	if stdout.String() != "public:0:0:tag\n" {
		t.Fatalf("public ABI stdout %q\n%s", stdout.String(), renamed)
	}
	denials := strings.Count(stderr.String(), "agentic action requires an explicit agentic")
	if denials != 1 {
		t.Fatalf("want one denial, got %d: %q", denials, stderr.String())
	}
	if status != 0 {
		t.Fatalf("status %d stderr %q", status, stderr.String())
	}
}

// TestRuntimeMethodResolutionDiagnostics covers the resolution rules that a
// substring test cannot: a name shared by several receivers is never guessed
// at, and the interface's own specification supplies the capability signature.
func TestRuntimeMethodResolutionDiagnostics(t *testing.T) {
	source := `type A struct { n int }
type B struct { n int }
agentic func (a *A) tag(label string) { echo "A:$label" }
agentic func (b *B) tag(count int) { printf 'B:%d\n' "$count" }
type I interface { tag(string) }
var x A = A{}
var y B = B{}
agentic { x.tag(one); }
`
	file := parseMethodFixture(t, source)
	unit := newMethodUnit(file)
	e := unit.e
	call := &syntax.BashPPCall{Fun: []*syntax.Lit{{Value: "x"}, {Value: "tag"}}}

	// A resolved receiver picks that receiver's declaration and signature.
	got, err := e.runtimeMethodCall(call, "A")
	if err != nil {
		t.Fatal(err)
	}
	if want := "x.__bpp0_call_tag(__bpp0_program, __bpp0_rt.Site{Name:\"tag\"})"; got != want {
		t.Fatalf("got %q want %q", got, want)
	}
	if got, err := e.runtimeMethodCall(call, "*B"); err != nil || !strings.Contains(got, "x.__bpp0_call_tag") {
		t.Fatalf("pointer receiver spelling: %q %v", got, err)
	}

	// An unresolved receiver for a name two types declare is a diagnostic, not
	// a guess at the first declaration.
	_, err = e.runtimeMethodCall(call, "")
	var list ErrorList
	if !errors.As(err, &list) || len(list) == 0 || list[0].Code != CodeType {
		t.Fatalf("ambiguous receiver: %v", err)
	}
	if _, err := e.runtimeMethodHandle(call, "x", "", "tag"); !errors.As(err, &list) || list[0].Code != CodeType {
		t.Fatalf("ambiguous handle receiver: %v", err)
	}

	// The interface's specification is what the capability interface states,
	// so an implementation is recognised by that signature and not by A's.
	through, err := e.runtimeMethodCall(call, "I")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(through, "interface{ __bpp0_call_tag(*__bpp0_rt.Program, __bpp0_rt.Site, string) }") {
		t.Fatalf("capability interface: %s", through)
	}
	// A zero-result private call must return rather than fall through into the
	// public method, which would repeat the method's effects.
	if strings.Count(through, "return") != 2 {
		t.Fatalf("private branch does not return: %s", through)
	}
	if _, err := e.runtimeMethodCall(call, "I"); err != nil {
		t.Fatal(err)
	}
	if _, _, found, err := e.interfaceMethodTypes(mustInterface(t, e, "I"), "missing", map[*syntax.BashPPInterfaceType]bool{}); found || err != nil {
		t.Fatalf("unknown interface method: %v %v", found, err)
	}

	// A method this unit does not declare is an ordinary Go call with no
	// private ABI and therefore no assistance.
	foreign := &syntax.BashPPCall{Fun: []*syntax.Lit{{Value: "x"}, {Value: "Unknown"}}}
	if got, err := e.runtimeMethodCall(foreign, "A"); err != nil || got != "x.Unknown()" {
		t.Fatalf("foreign call: %q %v", got, err)
	}
	if _, err := e.runtimeMethodHandle(foreign, "x", "A", "Unknown"); !errors.As(err, &list) || list[0].Code != CodeUnsupported {
		t.Fatalf("foreign handle: %v", err)
	}
}

func mustInterface(t *testing.T, e *emitter, name string) *syntax.BashPPInterfaceType {
	t.Helper()
	iface, ok := e.interfaceDecl(name)
	if !ok {
		t.Fatalf("%s is not a declared interface", name)
	}
	return iface
}

// TestRuntimeMethodDeclarationDiagnostics keeps the declaration hook's refusals
// positioned rather than emitting Go that cannot compile.
func TestRuntimeMethodDeclarationDiagnostics(t *testing.T) {
	e := newMethodUnit(parseMethodFixture(t, "agentic { echo hi; }\n")).e
	var list ErrorList
	kw := &syntax.Lit{Value: "func"}
	if _, err := e.runtimeMethodFunction(&syntax.BashPPFuncDecl{Kw: kw, Name: &syntax.Lit{Value: "m"}}, "()", "", ""); !errors.As(err, &list) || list[0].Code != CodeUnsupported {
		t.Fatalf("missing receiver: %v", err)
	}
	// A method's OWN type parameters are lowered, not refused: Go 1.27 accepts
	// them. Both halves of the pair carry the list, and the wrapper
	// instantiates the private half explicitly so a parameter that appears
	// only in the results is still spelled.
	generic := &syntax.BashPPFuncDecl{
		Kw:         kw,
		Name:       &syntax.Lit{Value: "m"},
		Receiver:   &syntax.BashPPReceiver{Name: &syntax.Lit{Value: "v"}, RecvType: &syntax.Lit{Value: "T"}},
		TypeParams: []*syntax.BashPPTypeParam{{Names: []*syntax.Lit{{Value: "X"}}}},
	}
	got, err := e.runtimeMethodFunction(generic, "()", "", "[X any]")
	if err != nil {
		t.Fatalf("method type parameters: %v", err)
	}
	for _, want := range []string{
		"func (v T) " + e.methodPrivateName("m") + "[X any](",
		"func (v T) m[X any]()",
		"v." + e.methodPrivateName("m") + "[X](",
	} {
		if !strings.Contains(got, want) {
			t.Fatalf("generic method lowering = %q, want to contain %q", got, want)
		}
	}
	unnamed := &syntax.BashPPFuncDecl{
		Kw:       kw,
		Name:     &syntax.Lit{Value: "m"},
		Receiver: &syntax.BashPPReceiver{Name: &syntax.Lit{Value: "v"}, RecvType: &syntax.Lit{Value: "T"}},
		Params:   []*syntax.BashPPField{{FieldType: &syntax.Lit{Value: "int"}}},
	}
	if _, err := e.runtimeMethodFunction(unnamed, "(int)", "", ""); !errors.As(err, &list) || list[0].Code != CodeUnsupported {
		t.Fatalf("unnamed parameter: %v", err)
	}
	if _, err := e.runtimeMethodCall(&syntax.BashPPCall{Fun: []*syntax.Lit{{Value: "x"}}}, "A"); !errors.As(err, &list) || list[0].Code != CodeExpr {
		t.Fatalf("selector arity: %v", err)
	}
}

// TestRuntimeMethodForeignImplementationRunsWithoutAssistance covers the branch
// no Bash++ source can reach: an interface value whose dynamic type was never
// compiled by this compiler and therefore carries no private method. The
// capability assertion fails and the public method runs, with assistance off.
// It also pins the defect the private branch's return exists for — a marked
// method reached without an agentic caller is denied once, not twice.
func TestRuntimeMethodForeignImplementationRunsWithoutAssistance(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 4*time.Minute)
	defer cancel()
	file := parseMethodFixture(t, `type T int
agentic func (v T) Show() { echo shown }
type I interface { Show() }
agentic { echo warm; }
`)
	unit := newMethodUnit(file)
	e := unit.e
	var decl *syntax.BashPPFuncDecl
	for _, s := range file.Stmts {
		if f, ok := s.Cmd.(*syntax.BashPPFuncDecl); ok && f.Receiver != nil {
			decl = f
		}
	}
	method, err := unit.function(decl)
	if err != nil {
		t.Fatal(err)
	}
	call := &syntax.BashPPCall{Fun: []*syntax.Lit{{Value: "i"}, {Value: "Show"}}}
	e.programExpr = "block"
	inside, err := e.runtimeMethodCall(call, "I")
	if err != nil {
		t.Fatal(err)
	}
	handle, err := e.runtimeMethodHandle(call, "i", "I", "Show")
	if err != nil {
		t.Fatal(err)
	}
	handleType, err := e.runtimeMethodHandleType(call, "I", "Show")
	if err != nil {
		t.Fatal(err)
	}
	e.programExpr = "program"
	outside, err := e.runtimeMethodCall(call, "I")
	if err != nil {
		t.Fatal(err)
	}
	source := `package main

import (
	__bpp0_fmt "fmt"
	__bpp0_os "os"
	__bpp0_rt "mvdan.cc/sh/v3/lower/shellrt"
)

type T int
type I interface{ Show() }
type Foreign struct{}

func (Foreign) Show() { __bpp0_fmt.Println("foreign") }

` + method + `
func main() {
	__bpp0_program, err := __bpp0_rt.NewProgram()
	if err != nil {
		__bpp0_fmt.Fprintln(__bpp0_os.Stderr, err)
		__bpp0_os.Exit(1)
	}
	err = __bpp0_program.Run(func(program *__bpp0_rt.Program) {
		block := program.Block()
		var i I = T(1)
		` + inside + `
		var compiled ` + handleType + ` = ` + handle + `
		i = Foreign{}
		` + inside + `
		var foreign ` + handleType + ` = ` + handle + `
		i = T(1)
		` + outside + `
		i = Foreign{}
		` + outside + `
		compiled(block, __bpp0_rt.Site{Name: "Show"})
		foreign(block, __bpp0_rt.Site{Name: "Show"})
	})
	if err != nil {
		__bpp0_program.Fail(err)
	}
	if status := __bpp0_program.Status(); status != 0 {
		__bpp0_os.Exit(status)
	}
}
`
	formatted, err := format.Source([]byte(source))
	if err != nil {
		t.Fatalf("harness does not parse: %v\n%s", err, source)
	}
	got := runMethodArtifact(t, ctx, formatted)
	// The compiled implementation keeps its marker through the interface, the
	// foreign one has no marker to keep, and each handle resolves the branch its
	// receiver had when it was captured.
	want := methodOutcome{
		stdout: "shown\nforeign\nforeign\nshown\nforeign\n",
		stderr: "Show: agentic action requires an explicit agentic { ...; } scope\n",
	}
	if got != want {
		t.Fatalf("got %+v want %+v\n%s", got, want, formatted)
	}
}

